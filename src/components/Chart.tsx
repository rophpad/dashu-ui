"use client";

import { ImageDown } from "lucide-react";
import { useMemo, useState } from "react";
import type { Cell, ChartSpec, ChartType } from "./types";

type Props = {
  spec: ChartSpec;
  columns: string[];
  rows: Cell[][];
  pro?: boolean;
};

type Point = { label: string; value: number; xValue: number | null };

const MAX_POINTS = 30;
const MAX_SLICES = 8;

function toNumber(value: Cell): number | null {
  if (typeof value === "number") return Number.isFinite(value) ? value : null;
  if (typeof value === "string") {
    // Postgres returns numeric/bigint as strings to preserve precision.
    const n = Number(value.replace(/,/g, ""));
    return value.trim() !== "" && Number.isFinite(n) ? n : null;
  }
  return null;
}

function toLabel(value: Cell): string {
  if (value === null) return "—";
  if (typeof value === "string") {
    const iso = /^(\d{4}-\d{2}-\d{2})T/.exec(value);
    return iso ? iso[1] : value;
  }
  return String(value);
}

function formatValue(n: number): string {
  const abs = Math.abs(n);
  if (abs >= 1_000_000_000) return `${(n / 1_000_000_000).toFixed(1)}B`;
  if (abs >= 1_000_000) return `${(n / 1_000_000).toFixed(1)}M`;
  if (abs >= 10_000) return `${(n / 1_000).toFixed(1)}K`;
  return Number.isInteger(n) ? n.toLocaleString() : n.toFixed(2);
}

/**
 * Grayscale ramp for categorical marks. A monochrome palette has to earn its
 * separation from lightness alone, so slices step from near-black to light gray
 * with a white divider between them.
 */
const SERIES = [
  "var(--color-s1)",
  "var(--color-s2)",
  "var(--color-s3)",
  "var(--color-s4)",
  "var(--color-s5)",
  "var(--color-s6)",
  "var(--color-s7)",
  "var(--color-s8)",
];

/**
 * Categorical hues in fixed order, never cycled — a slice keeps its colour
 * regardless of how many others are present. The order is validated for
 * colour-vision deficiency, and the legend carries text labels and values so
 * identity is never colour alone.
 */
function shade(index: number): string {
  return SERIES[index % SERIES.length];
}

const LABELS: Record<Exclude<ChartType, "none">, string> = {
  bar: "Bar",
  line: "Line",
  area: "Area",
  pie: "Pie",
  scatter: "Scatter",
};

/**
 * Hand-rolled SVG rather than a charting library: the visual language here is
 * one weight of black on a neutral scale, which every library fights you on.
 */
function themeColor(name: string, fallback: string): string {
  return getComputedStyle(document.documentElement).getPropertyValue(name).trim() || fallback;
}

function fitLabel(context: CanvasRenderingContext2D, label: string, maxWidth: number): string {
  if (context.measureText(label).width <= maxWidth) return label;
  let shortened = label;
  while (shortened.length > 1 && context.measureText(`${shortened}…`).width > maxWidth) {
    shortened = shortened.slice(0, -1);
  }
  return `${shortened}…`;
}

async function downloadChartAsPng(
  points: Point[],
  spec: ChartSpec,
  type: Exclude<ChartType, "none">,
) {
  const width = 1200;
  const height = 675;
  const canvas = document.createElement("canvas");
  canvas.width = width;
  canvas.height = height;
  const context = canvas.getContext("2d");
  if (!context) throw new Error("Canvas is not supported by this browser.");

  const background = themeColor("--color-panel", "#ffffff");
  const foreground = themeColor("--color-fg", "#000000");
  const muted = themeColor("--color-muted", "#666666");
  const accent = themeColor("--color-accent", "#2a78d6");
  const surface = themeColor("--color-surface-hover", "#f2f2f2");
  const series = Array.from({ length: 8 }, (_, index) =>
    themeColor(`--color-s${index + 1}`, accent),
  );

  context.fillStyle = background;
  context.fillRect(0, 0, width, height);
  context.fillStyle = foreground;
  context.font = "600 30px system-ui, sans-serif";
  context.fillText(`${spec.valueColumn} by ${spec.labelColumn}`, 64, 62);
  context.fillStyle = muted;
  context.font = "18px system-ui, sans-serif";
  context.fillText(`${LABELS[type]} chart · generated by Dashu`, 64, 94);

  const left = 80;
  const top = 135;
  const plotWidth = width - 160;
  const plotHeight = height - 215;

  if (type === "bar") {
    const shown = points.slice(0, 12);
    const max = Math.max(...shown.map((point) => point.value), 0) || 1;
    const rowHeight = plotHeight / shown.length;
    const labelWidth = 230;
    shown.forEach((point, index) => {
      const y = top + index * rowHeight + rowHeight / 2;
      context.font = "17px system-ui, sans-serif";
      context.fillStyle = muted;
      context.textAlign = "right";
      context.fillText(fitLabel(context, point.label, labelWidth - 20), left + labelWidth, y + 6);
      context.fillStyle = surface;
      context.fillRect(left + labelWidth + 20, y - 9, plotWidth - labelWidth - 120, 18);
      context.fillStyle = accent;
      context.fillRect(
        left + labelWidth + 20,
        y - 9,
        Math.max(2, (point.value / max) * (plotWidth - labelWidth - 120)),
        18,
      );
      context.fillStyle = foreground;
      context.textAlign = "right";
      context.fillText(formatValue(point.value), left + plotWidth, y + 6);
    });
  } else if (type === "pie") {
    const sorted = [...points].sort((a, b) => b.value - a.value);
    const slices = sorted.length > MAX_SLICES
      ? [
          ...sorted.slice(0, MAX_SLICES - 1),
          {
            label: `Other (${sorted.length - MAX_SLICES + 1})`,
            value: sorted.slice(MAX_SLICES - 1).reduce((sum, point) => sum + point.value, 0),
            xValue: null,
          },
        ]
      : sorted;
    const total = slices.reduce((sum, point) => sum + point.value, 0);
    let angle = -Math.PI / 2;
    const centerX = 350;
    const centerY = top + plotHeight / 2;
    const radius = 190;
    slices.forEach((slice, index) => {
      const next = angle + (slice.value / total) * Math.PI * 2;
      context.beginPath();
      context.moveTo(centerX, centerY);
      context.arc(centerX, centerY, radius, angle, next);
      context.closePath();
      context.fillStyle = series[index % series.length];
      context.fill();
      angle = next;

      const legendY = top + 30 + index * 52;
      context.fillRect(650, legendY - 15, 22, 22);
      context.fillStyle = foreground;
      context.font = "18px system-ui, sans-serif";
      context.textAlign = "left";
      context.fillText(fitLabel(context, slice.label, 280), 690, legendY + 3);
      context.textAlign = "right";
      context.fillText(`${formatValue(slice.value)} · ${((slice.value / total) * 100).toFixed(1)}%`, 1120, legendY + 3);
    });
  } else {
    const values = points.map((point) => point.value);
    const min = Math.min(...values, 0);
    const max = Math.max(...values, 0);
    const span = max - min || 1;
    const xValues = points.map((point) => point.xValue).filter((value): value is number => value !== null);
    const xMin = xValues.length ? Math.min(...xValues) : 0;
    const xMax = xValues.length ? Math.max(...xValues) : points.length - 1;
    const xSpan = xMax - xMin || 1;
    const coordinates = points.map((point, index) => ({
      x: left + (type === "scatter"
        ? (((point.xValue as number) - xMin) / xSpan) * plotWidth
        : (index / Math.max(points.length - 1, 1)) * plotWidth),
      y: top + plotHeight - ((point.value - min) / span) * plotHeight,
      point,
    }));

    context.strokeStyle = surface;
    context.lineWidth = 2;
    context.beginPath();
    context.moveTo(left, top + plotHeight);
    context.lineTo(left + plotWidth, top + plotHeight);
    context.stroke();

    if (type !== "scatter") {
      context.beginPath();
      coordinates.forEach(({ x, y }, index) => index ? context.lineTo(x, y) : context.moveTo(x, y));
      if (type === "area") {
        context.lineTo(left + plotWidth, top + plotHeight);
        context.lineTo(left, top + plotHeight);
        context.closePath();
        context.globalAlpha = 0.18;
        context.fillStyle = accent;
        context.fill();
        context.globalAlpha = 1;
      }
      context.beginPath();
      coordinates.forEach(({ x, y }, index) => index ? context.lineTo(x, y) : context.moveTo(x, y));
      context.strokeStyle = accent;
      context.lineWidth = 5;
      context.lineJoin = "round";
      context.lineCap = "round";
      context.stroke();
    }

    context.fillStyle = accent;
    coordinates.forEach(({ x, y }) => {
      context.beginPath();
      context.arc(x, y, type === "scatter" ? 7 : 5, 0, Math.PI * 2);
      context.fill();
    });
    context.font = "17px system-ui, sans-serif";
    context.fillStyle = muted;
    context.textAlign = "left";
    context.fillText(points[0].label, left, height - 40);
    context.textAlign = "right";
    context.fillText(points[points.length - 1].label, left + plotWidth, height - 40);
  }

  const blob = await new Promise<Blob>((resolve, reject) => {
    canvas.toBlob(
      (value) => value ? resolve(value) : reject(new Error("The browser could not create the PNG.")),
      "image/png",
    );
  });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `dashu-chart-${new Date().toISOString().slice(0, 10)}.png`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 0);
}

export default function Chart({ spec, columns, rows, pro = false }: Props) {
  const [override, setOverride] = useState<ChartType | null>(null);
  const [exporting, setExporting] = useState(false);
  const [exportError, setExportError] = useState<string | null>(null);

  const points = useMemo<Point[]>(() => {
    const labelIdx = columns.indexOf(spec.labelColumn);
    const valueIdx = columns.indexOf(spec.valueColumn);
    if (labelIdx === -1 || valueIdx === -1) return [];

    return rows
      .map((row) => ({
        label: toLabel(row[labelIdx]),
        value: toNumber(row[valueIdx]),
        xValue: toNumber(row[labelIdx]),
      }))
      .filter((p): p is Point => p.value !== null)
      .slice(0, MAX_POINTS);
  }, [columns, rows, spec.labelColumn, spec.valueColumn]);

  const available = useMemo<Exclude<ChartType, "none">[]>(() => {
    if (points.length < 2) return [];
    const types: Exclude<ChartType, "none">[] = ["bar", "line", "area"];
    // Pie only makes sense for a composition: non-negative parts of one whole.
    if (points.every((p) => p.value >= 0) && points.some((p) => p.value > 0)) {
      types.push("pie");
    }
    if (points.every((p) => p.xValue !== null)) types.push("scatter");
    return types;
  }, [points]);

  if (spec.type === "none" || points.length < 2 || available.length === 0) return null;

  // The model proposes; if its choice doesn't fit the data, fall back to bar.
  const requested = override ?? spec.type;
  const type: Exclude<ChartType, "none"> =
    requested !== "none" && available.includes(requested) ? requested : "bar";

  async function exportPng() {
    if (exporting) return;
    setExporting(true);
    setExportError(null);
    try {
      await downloadChartAsPng(points, spec, type);
    } catch (error) {
      setExportError(error instanceof Error ? error.message : "Could not export this chart.");
    } finally {
      setExporting(false);
    }
  }

  return (
    <figure className="mt-4 rounded-lg border bg-surface px-4 pb-4 pt-3">
      <figcaption className="mb-3 flex flex-wrap items-center justify-between gap-2">
        <span className="text-xs font-medium text-muted">
          {spec.valueColumn} by {spec.labelColumn}
        </span>
        <span className="flex items-center gap-1">
          {pro && (
            <button
              type="button"
              onClick={() => void exportPng()}
              disabled={exporting}
              aria-label="Save chart as PNG"
              title="Save chart as PNG"
              className="rounded-md p-1.5 text-muted transition-colors hover:bg-panel hover:text-fg disabled:opacity-40"
            >
              <ImageDown size={14} aria-hidden="true" />
            </button>
          )}
          {available.length > 1 && (
            <span className="flex items-center gap-0.5 rounded-lg border bg-panel p-0.5">
              {available.map((t) => (
                <button
                  key={t}
                  type="button"
                  onClick={() => setOverride(t)}
                  aria-pressed={t === type}
                  className={`rounded-md px-2 py-1 text-[11px] font-medium transition-colors ${
                    t === type
                      ? "bg-accent text-white"
                      : "text-muted hover:bg-surface hover:text-fg"
                  }`}
                >
                  {LABELS[t as Exclude<ChartType, "none">]}
                </button>
              ))}
            </span>
          )}
        </span>
      </figcaption>
      {exportError && (
        <p role="alert" className="mb-3 text-xs text-red-600 dark:text-red-400">{exportError}</p>
      )}

      {type === "bar" && <BarChart points={points} />}
      {type === "pie" && <PieChart points={points} />}
      {type === "scatter" && <ScatterChart points={points} spec={spec} />}
      {(type === "line" || type === "area") && (
        <LineChart points={points} filled={type === "area"} />
      )}
    </figure>
  );
}

