function BarChart({ points }: { points: Point[] }) {
  const max = Math.max(...points.map((p) => p.value), 0);

  return (
    <div className="flex flex-col gap-2.5">
      {points.map((p, i) => (
        <div key={`${p.label}-${i}`} className="flex items-center gap-3 text-xs">
          <span className="w-28 shrink-0 truncate text-right text-muted" title={p.label}>
            {p.label}
          </span>
          <span className="relative h-2 flex-1 overflow-hidden rounded-full bg-panel">
            <span
              className="absolute inset-y-0 left-0 rounded-full bg-accent"
              style={{ width: `${max > 0 ? Math.max((p.value / max) * 100, 1.5) : 0}%` }}
            />
          </span>
          <span className="w-16 shrink-0 text-right font-mono font-medium tabular-nums">
            {formatValue(p.value)}
          </span>
        </div>
      ))}
    </div>
  );
}

