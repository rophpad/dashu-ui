function arcPath(
  cx: number,
  cy: number,
  outer: number,
  inner: number,
  start: number,
  end: number,
): string {
  const large = end - start > Math.PI ? 1 : 0;
  const x0 = cx + outer * Math.cos(start);
  const y0 = cy + outer * Math.sin(start);
  const x1 = cx + outer * Math.cos(end);
  const y1 = cy + outer * Math.sin(end);
  const xi1 = cx + inner * Math.cos(end);
  const yi1 = cy + inner * Math.sin(end);
  const xi0 = cx + inner * Math.cos(start);
  const yi0 = cy + inner * Math.sin(start);
  return [
    `M${x0} ${y0}`,
    `A${outer} ${outer} 0 ${large} 1 ${x1} ${y1}`,
    `L${xi1} ${yi1}`,
    `A${inner} ${inner} 0 ${large} 0 ${xi0} ${yi0}`,
    "Z",
  ].join(" ");
}

function PieChart({ points }: { points: Point[] }) {
  // Too many slices is unreadable; roll the tail into one "Other".
  const sorted = [...points].sort((a, b) => b.value - a.value);
  const slices =
    sorted.length > MAX_SLICES
      ? [
          ...sorted.slice(0, MAX_SLICES - 1),
          {
            label: `Other (${sorted.length - MAX_SLICES + 1})`,
            value: sorted.slice(MAX_SLICES - 1).reduce((n, p) => n + p.value, 0),
            xValue: null,
          },
        ]
      : sorted;

  const total = slices.reduce((n, s) => n + s.value, 0);
  if (total <= 0) return null;

  const size = 168;
  const c = size / 2;
  const outer = 78;
  const inner = 46;

  let angle = -Math.PI / 2; // start at twelve o'clock
  const wedges = slices.map((slice, i) => {
    const sweep = (slice.value / total) * Math.PI * 2;
    const start = angle;
    angle += sweep;
    return { ...slice, start, end: angle, fill: shade(i), sweep };
  });

  return (
    <div className="flex flex-wrap items-center gap-x-6 gap-y-4">
      <svg
        viewBox={`0 0 ${size} ${size}`}
        className="h-44 w-44 shrink-0"
        role="img"
        aria-label="Pie chart"
      >
        {wedges.length === 1 ? (
          <circle
            cx={c}
            cy={c}
            r={(outer + inner) / 2}
            fill="none"
            stroke={wedges[0].fill}
            strokeWidth={outer - inner}
          />
        ) : (
          wedges.map((w, i) => (
            <path
              key={i}
              d={arcPath(c, c, outer, inner, w.start, w.end)}
              fill={w.fill}
              stroke="var(--color-panel)"
              strokeWidth={1.5}
            >
              <title>{`${w.label}: ${formatValue(w.value)} (${((w.value / total) * 100).toFixed(1)}%)`}</title>
            </path>
          ))
        )}
        <text
          x={c}
          y={c - 2}
          textAnchor="middle"
          className="fill-current text-[15px] font-medium"
          style={{ fontVariantNumeric: "tabular-nums" }}
        >
          {formatValue(total)}
        </text>
        <text x={c} y={c + 13} textAnchor="middle" className="fill-current text-[9px] opacity-50">
          total
        </text>
      </svg>

      <ul className="min-w-0 flex-1 space-y-1.5">
        {wedges.map((w, i) => (
          <li key={i} className="flex items-center gap-2 text-xs">
            <span
              className="h-2.5 w-2.5 shrink-0 rounded-sm"
              style={{ background: w.fill }}
            />
            <span className="min-w-0 flex-1 truncate text-muted" title={w.label}>
              {w.label}
            </span>
            <span className="shrink-0 font-mono tabular-nums">{formatValue(w.value)}</span>
            <span className="w-11 shrink-0 text-right tabular-nums text-faint">
              {((w.value / total) * 100).toFixed(1)}%
            </span>
          </li>
        ))}
      </ul>
    </div>
  );
}

