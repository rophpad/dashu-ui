function ScatterChart({ points, spec }: { points: Point[]; spec: ChartSpec }) {
  const { width, height, padY } = PLOT;
  const padX = 10;

  const xs = points.map((p) => p.xValue as number);
  const ys = points.map((p) => p.value);
  const xMin = Math.min(...xs);
  const xMax = Math.max(...xs);
  const yMin = Math.min(...ys, 0);
  const yMax = Math.max(...ys, 0);
  const xSpan = xMax - xMin || 1;
  const ySpan = yMax - yMin || 1;

  const coords = points.map((p) => ({
    cx: padX + ((p.xValue as number) - xMin) / xSpan * (width - padX * 2),
    cy: height - padY - ((p.value - yMin) / ySpan) * (height - padY * 2),
    ...p,
  }));

  return (
    <>
      <svg
        viewBox={`0 0 ${width} ${height}`}
        className="h-44 w-full overflow-visible"
        preserveAspectRatio="none"
        role="img"
        aria-label="Scatter plot"
      >
        <line
          x1={0}
          y1={height - padY}
          x2={width}
          y2={height - padY}
          stroke="rgb(0 0 0 / 0.15)"
          strokeWidth={1}
          vectorEffect="non-scaling-stroke"
        />
        {coords.map((c, i) => (
          <circle key={i} cx={c.cx} cy={c.cy} r={3} fill="var(--color-accent)">
            <title>{`${spec.labelColumn} ${c.label} · ${spec.valueColumn} ${formatValue(c.value)}`}</title>
          </circle>
        ))}
      </svg>
      <div className="mt-2.5 flex justify-between text-xs text-faint">
        <span className="font-mono tabular-nums">{formatValue(xMin)}</span>
        <span>{spec.labelColumn} →</span>
        <span className="font-mono tabular-nums">{formatValue(xMax)}</span>
      </div>
    </>
  );
}
