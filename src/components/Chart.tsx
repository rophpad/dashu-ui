const PLOT = { width: 720, height: 180, padX: 4, padY: 14 };

function LineChart({ points, filled }: { points: Point[]; filled: boolean }) {
  const { width, height, padX, padY } = PLOT;
  const values = points.map((p) => p.value);
  const max = Math.max(...values, 0);
  const min = Math.min(...values, 0);
  const span = max - min || 1;
  const stepX = (width - padX * 2) / (points.length - 1);

  const coords = points.map((p, i) => ({
    x: padX + i * stepX,
    y: height - padY - ((p.value - min) / span) * (height - padY * 2),
    ...p,
  }));

  const line = coords.map((c, i) => `${i === 0 ? "M" : "L"}${c.x} ${c.y}`).join(" ");
  const area = `${line} L${coords[coords.length - 1].x} ${height} L${coords[0].x} ${height} Z`;

  return (
    <>
      <svg
        viewBox={`0 0 ${width} ${height}`}
        className="h-44 w-full overflow-visible"
        preserveAspectRatio="none"
        role="img"
        aria-label={filled ? "Area chart" : "Line chart"}
      >
        <path d={area} fill={filled ? "var(--color-accent)" : "var(--color-accent)"}
          fillOpacity={filled ? 0.16 : 0.06} />
        <path
          d={line}
          fill="none"
          stroke="var(--color-accent)"
          strokeWidth={2}
          strokeLinecap="round"
          strokeLinejoin="round"
          vectorEffect="non-scaling-stroke"
        />
        {!filled &&
          coords.map((c, i) => (
            <circle key={i} cx={c.x} cy={c.y} r={4} fill="var(--color-accent)" stroke="var(--color-panel)" strokeWidth={1.5}>
              <title>{`${c.label}: ${formatValue(c.value)}`}</title>
            </circle>
          ))}
      </svg>
      <div className="mt-2.5 flex justify-between text-xs text-faint">
        <span>{points[0].label}</span>
        <span className="font-mono tabular-nums">
          {formatValue(min)} – {formatValue(max)}
        </span>
        <span>{points[points.length - 1].label}</span>
      </div>
    </>
  );
}

